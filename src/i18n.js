const staticLabels = [];
const labelAttributes = ['aria-label', 'placeholder', 'title'];
function captureStaticLabels(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (Object.hasOwn(english, node.data.trim())) {
      const key = node.data.trim();
      const original = node.data;
      staticLabels.push(() => { node.data = original.replace(key, () => t(key)); });
      if (node.parentElement.matches('option:not([value])')) node.parentElement.value = key;
    }
  }
  for (const el of root.querySelectorAll('[aria-label], [placeholder], [title]')) {
    for (const attr of labelAttributes) {
      const key = el.getAttribute(attr);
      if (Object.hasOwn(english, key)) staticLabels.push(() => el.setAttribute(attr, t(key)));
    }
  }
}
function applyStaticLanguage() {
  document.documentElement.lang = language;
  for (const update of staticLabels) update();
}
